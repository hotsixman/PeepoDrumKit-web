const Tables: (Record<string, string> | null)[] = [null, JA, KO];

export const LanguageState = { Selected: GuiLanguage.EN, Version: 0 };

export function SetGuiLanguage(language: GuiLanguage): void { LanguageState.Selected = language; LanguageState.Version++; }

export function DetectDefaultGuiLanguage(): GuiLanguage
{
	const lang = (typeof navigator !== "undefined") ? navigator.language.toLowerCase() : "en";
	if (lang.startsWith("ja")) return GuiLanguage.JA;
	if (lang.startsWith("ko")) return GuiLanguage.KO;
	return GuiLanguage.EN;
}

/** NOTE: Equivalent of UI_Str() / UI_StrRuntime() */
export function UI_Str(english: string): string
{
	const table = Tables[LanguageState.Selected];
	return (table !== null) ? (table[english] ?? english) : english;
}

/** NOTE: printf style "%s" / "%d" replacement for translated format strings */
export function UI_Fmt(english: string, ...args: (string | number)[]): string
{
	let i = 0;
	return UI_Str(english).replace(/%[sdg]/g, () => String(args[i++] ?? ""));
}
